#!/usr/bin/env node
/*
 * Build step. There is no bundler: the app runs straight from these files.
 * This script generates two things from the course data:
 *   data/index.js   small summary of every module so the home screen loads fast
 *   sw.js           service worker with the exact file list and a content hash
 *
 * Run it after changing anything in data/, js/, css/, fonts/ or icons/.
 *   node scripts/build.js
 */
'use strict';

var fs = require('fs');
var path = require('path');
var crypto = require('crypto');
var validate = require('../tests/validate.js');

var ROOT = path.resolve(__dirname, '..');

function words(s) {
  var t = String(s).replace(/\*\*|`/g, ' ').trim();
  return t ? t.split(/\s+/).length : 0;
}

function lessonWords(l) {
  var n = 0;
  l.body.forEach(function (b) {
    if (b.text) n += words(b.text);
    if (b.items) b.items.forEach(function (i) { n += words(i); });
    if (b.steps) b.steps.forEach(function (i) { n += words(i); });
  });
  return n;
}

function buildIndex() {
  var res = validate.run();
  if (res.errors.length) {
    console.error('Content has errors; fix them before building:');
    res.errors.forEach(function (e) { console.error('  x ' + e); });
    process.exit(1);
  }
  var course = res.course;
  var modules = {};
  var order = [];
  var totals = { lessons: 0, minutes: 0, quiz: 0, cards: 0, words: 0 };
  course.modules.forEach(function (cm) {
    var m = res.modules[cm.id];
    var minutes = 0, w = 0;
    var lessons = m.lessons.map(function (l) {
      minutes += l.minutes;
      w += lessonWords(l);
      return { id: l.id, title: l.title, minutes: l.minutes };
    });
    modules[cm.id] = {
      id: cm.id,
      number: cm.number,
      area: cm.area,
      title: cm.title,
      short: cm.short,
      summary: m.summary,
      lessons: lessons,
      minutes: minutes,
      words: w,
      quiz: m.quiz.length,
      cards: m.cards.length
    };
    order.push(cm.id);
    totals.lessons += lessons.length;
    totals.minutes += minutes;
    totals.quiz += m.quiz.length;
    totals.cards += m.cards.length;
    totals.words += w;
  });
  var out = {
    order: order,
    modules: modules,
    totals: totals,
    faults: res.faults.length,
    examPool: totals.quiz
  };
  var src = '/* Generated by scripts/build.js. Do not edit by hand. */\n' +
    'window.MVM = window.MVM || {};\n' +
    'window.MVM.index = ' + JSON.stringify(out, null, 1) + ';\n';
  fs.writeFileSync(path.join(ROOT, 'data/index.js'), src);
  console.log('data/index.js  ' + order.length + ' modules, ' + totals.quiz + ' questions, ' + totals.cards + ' cards, ' + totals.minutes + ' min of lessons');
  return out;
}

function walk(dir, base, out) {
  fs.readdirSync(dir).forEach(function (name) {
    var full = path.join(dir, name);
    var rel = path.posix.join(base, name);
    var st = fs.statSync(full);
    if (st.isDirectory()) walk(full, rel, out);
    else out.push(rel);
  });
  return out;
}

function buildServiceWorker() {
  var files = [];
  ['css', 'js', 'data', 'fonts', 'icons'].forEach(function (d) {
    walk(path.join(ROOT, d), d, files);
  });
  files = files.filter(function (f) { return !/package\.json$/.test(f); });
  files.push('index.html', 'manifest.webmanifest');
  files.sort();

  var hash = crypto.createHash('sha256');
  files.forEach(function (f) {
    hash.update(f);
    hash.update(fs.readFileSync(path.join(ROOT, f)));
  });
  var version = hash.digest('hex').slice(0, 12);

  var tpl = fs.readFileSync(path.join(ROOT, 'scripts/sw.template.js'), 'utf8');
  var src = tpl
    .replace('__VERSION__', version)
    .replace('__FILES__', JSON.stringify(files, null, 2));
  fs.writeFileSync(path.join(ROOT, 'sw.js'), src);

  var versionFile = 'window.MVM = window.MVM || {};\nwindow.MVM.build = ' + JSON.stringify({ version: version, files: files.length }) + ';\n';
  fs.writeFileSync(path.join(ROOT, 'data/build.js'), versionFile);
  console.log('sw.js          ' + files.length + ' files, version ' + version);
}

buildIndex();
/* data/build.js is part of the hashed file list, so write a placeholder first, then hash, then rewrite. */
fs.writeFileSync(path.join(ROOT, 'data/build.js'), 'window.MVM = window.MVM || {};\nwindow.MVM.build = { version: "dev", files: 0 };\n');
buildServiceWorker();
